    vi.useFakeTimers()
    const h=await harness(signedOut),wait=deferred<ReturnType<typeof ok>>()
    let starting: Promise<void> | undefined
    if (source === 'start') { h.api.start.mockReturnValueOnce(wait.promise);starting=h.account.start() }
    else { await h.account.start();h.api.status.mockReturnValueOnce(wait.promise);await vi.advanceTimersByTimeAsync(500) }
    cleanups.splice(0).forEach(clean=>clean())
    h.api.status.mockResolvedValue(ok(signedIn));cleanups.push(h.account.attach());await flush()
