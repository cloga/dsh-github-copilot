    const h=await harness(signedOut)
    if (failure === 'throw') h.api.start.mockRejectedValueOnce(new Error('PRIVATE'))
    else if (failure === 'invalid') h.api.start.mockResolvedValueOnce({ok:true,value:{phase:'invalid'}} as never)
