    vi.useFakeTimers()
    const h=await harness(signedOut)
    await h.account.start()
    h.api.status.mockResolvedValueOnce(ok({...signedIn,phase:'error',error:'PRIVATE'}))
    await vi.advanceTimersByTimeAsync(500)
